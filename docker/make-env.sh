#!/usr/bin/env bash
# Generates docker/.env with fresh random secrets. Adzuna keys are copied from the project's
# .env when it exists. Safe to re-run only if docker/.env does not exist yet.
set -euo pipefail
cd "$(dirname "$0")"

if [ -f .env ]; then
  echo "docker/.env already exists. Delete it first only if you want NEW secrets -"
  echo "note that a new POSTGRES_PASSWORD will not match an existing database volume."
  exit 1
fi

command -v openssl >/dev/null || { echo "openssl is required"; exit 1; }

# value of KEY from the project's own .env (quotes stripped); empty if missing
from_root() {
  [ -f ../.env ] || return 0
  grep -E "^$1=" ../.env | head -1 | cut -d= -f2- | sed -e "s/^['\"]//" -e "s/['\"]\$//" || true
}

# Postgres major version: at least 16, and never older than your local pg_dump - a dump taken
# with a NEWER major version cannot be restored by an older pg_restore.
pgv=16
local_pgv="$(pg_dump --version 2>/dev/null | grep -oE '[0-9]+' | head -1 || true)"
if [ -n "${local_pgv:-}" ] && [ "$local_pgv" -gt "$pgv" ]; then pgv="$local_pgv"; fi

uid=50000                                       # Docker Desktop (macOS/Windows)
if [ "$(uname -s)" = "Linux" ] && [ "$(id -u)" != "0" ]; then uid="$(id -u)"; fi   # Linux: files owned by you (never root)

umask 077
cat > .env <<ENVFILE
# Generated by make-env.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ). NEVER commit this file.

# --- database (pipeline data + Airflow metadata live in this Postgres) ---
POSTGRES_USER=pipeline
POSTGRES_PASSWORD=$(openssl rand -hex 16)
POSTGRES_HOST_PORT=5433
POSTGRES_VERSION=${pgv}

# --- Airflow ---
FERNET_KEY=$(openssl rand -base64 32 | tr '+/' '-_' | tr -d '\n')
JWT_SECRET=$(openssl rand -hex 32)
AIRFLOW_ADMIN_PASSWORD=$(openssl rand -hex 12)
API_HOST_PORT=8080
AIRFLOW_UID=${uid}

# --- Adzuna API ---
ADZUNA_APP_ID=$(from_root ADZUNA_APP_ID)
ADZUNA_APP_KEY=$(from_root ADZUNA_APP_KEY)

# --- pipeline ---
MIN_RAW_JOBS=1500

# --- Slack alerts (optional): the T000/B000/XXXX part of your Incoming Webhook URL ---
SLACK_WEBHOOK_TOKEN=
ENVFILE

echo "Wrote docker/.env"
grep -q '^ADZUNA_APP_ID=.\+' .env && grep -q '^ADZUNA_APP_KEY=.\+' .env \
  || echo "WARNING: ADZUNA_APP_ID / ADZUNA_APP_KEY are empty - edit docker/.env before starting."
echo "Airflow login:  admin / $(grep '^AIRFLOW_ADMIN_PASSWORD=' .env | cut -d= -f2)"
